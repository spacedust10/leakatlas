"""Aggregate queries over the stored audit. Every reported number comes from here.

Usage: uv run python -m leakatlas.analysis   (writes results/config_table.md and results/summary.md)
Requires `python -m leakatlas.proxies` to have stored the phase3_* tables first (`make reproduce` does both).
"""

from pathlib import Path

import numpy as np
import polars as pl
from scipy import stats as st

from leakatlas.store import connect, query

RESULTS = Path(__file__).resolve().parents[2] / "results"
T95 = st.t.ppf(0.975, 2)  # 3 seeds -> 2 degrees of freedom
LABEL = {"baseline": "Undefended (overfit)", "aof": "Anti-overfitting", "dp_eps1": "DP-SGD ε=1",
         "dp_eps4": "DP-SGD ε=4", "dp_eps8": "DP-SGD ε=8", "miashield": "MIAShield"}

DEFENSE_ORDER = ["baseline", "aof", "dp_eps1", "dp_eps4", "dp_eps8", "miashield"]


def config_table(con=None) -> pl.DataFrame:
    """Utility, attack success (mean ± std over seeds) and training cost per configuration."""
    con = con or connect(read_only=True)
    df = query(con, """
        SELECT r.dataset, r.defense, r.train_size, r.seed, r.test_acc, r.loss_ratio, r.eps_spent,
               r.train_sec, r.ref_train_sec, a.attack, a.auc, a.tpr_at_0p1, a.tpr_at_1,
               a.shadow_tpr_at_1, a.shadow_fpr_at_1
        FROM runs r JOIN attack_results a USING (run_id)""")
    stats = ["test_acc", "auc", "tpr_at_0p1", "tpr_at_1", "shadow_tpr_at_1", "shadow_fpr_at_1", "loss_ratio"]
    out = df.group_by("dataset", "defense", "train_size", "attack").agg(
        [pl.col(c).mean().alias(c) for c in stats]
        + [pl.col(c).std().alias(f"{c}_sd") for c in stats]
        + [pl.col("eps_spent").mean(), pl.col("train_sec").mean().alias("target_sec"),
           pl.col("ref_train_sec").first().alias("refs_sec"), pl.len().alias("seeds")])
    order = {d: i for i, d in enumerate(DEFENSE_ORDER)}
    return out.with_columns(pl.col("defense").replace_strict(order).alias("_o")).sort(
        "dataset", "train_size", "_o", "attack").drop("_o")


def markdown(df: pl.DataFrame) -> str:
    pm = lambda c, d=3, pct=False: (lambda r: (f"{100 * r[c]:.{d}f} ± {100 * r[c + '_sd']:.{d}f}" if pct
                                               else f"{r[c]:.{d}f} ± {r[c + '_sd']:.{d}f}"))
    head = ("| dataset | S | defense | ε spent (RDP) | attack | test acc | AUC | TPR@0.1% FPR (%) | TPR@1% FPR (%) "
            "| shadow-thr TPR / realized FPR @1% (%) | loss ratio | target s | refs s |")
    rows = [head, "|" + "---|" * 13]
    for r in df.iter_rows(named=True):
        eps = "–" if r["eps_spent"] is None else f"{r['eps_spent']:.2f}"
        rows.append(
            f"| {r['dataset']} | {r['train_size']} | {r['defense']} | {eps} | {r['attack']} | "
            f"{pm('test_acc')(r)} | {pm('auc')(r)} | {pm('tpr_at_0p1', 2, True)(r)} | {pm('tpr_at_1', 2, True)(r)} | "
            f"{100 * r['shadow_tpr_at_1']:.2f} / {100 * r['shadow_fpr_at_1']:.2f} | {pm('loss_ratio', 2)(r)} | "
            f"{r['target_sec']:.1f} | {r['refs_sec']:.0f} |")
    return "\n".join(rows)


def _ci(r, c, scale=1.0, d=1):
    """mean [95% t-interval over seeds]"""
    m, h = scale * r[c], scale * T95 * r[c + "_sd"] / np.sqrt(r["seeds"])
    return f"{m:.{d}f} [{m - h:.{d}f}, {m + h:.{d}f}]"


def _table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
                     + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def pareto(cfg: pl.DataFrame) -> list[str]:
    acc, tpr = cfg["test_acc"].to_numpy(), cfg["tpr_at_1"].to_numpy()
    return [d for d, a, t in zip(cfg["defense"], acc, tpr)
            if not np.any((acc >= a) & (tpr <= t) & ((acc > a) | (tpr < t)))]


def summary(con) -> str:
    ct = config_table(con)
    rmia, loss = ct.filter(pl.col("attack") == "rmia"), ct.filter(pl.col("attack") == "loss")
    n_rows = query(con, "SELECT count(*) n FROM record_scores")["n"][0]
    n_runs = query(con, "SELECT count(*) n FROM runs")["n"][0]
    refs = query(con, "SELECT dataset, max(num_refs_used) k FROM runs GROUP BY 1 ORDER BY 1")
    cost = query(con, """SELECT dataset, sum(train_sec) / 3600 AS target_h,
                                (SELECT sum(x) FROM (SELECT DISTINCT r2.train_size, r2.defense, r2.ref_train_sec x
                                 FROM runs r2 WHERE r2.dataset = r.dataset)) / 3600 AS refs_h
                         FROM runs r GROUP BY dataset ORDER BY dataset""")
    out = ["# LeakAtlas results summary", "",
           f"Generated by `make reproduce` (`leakatlas.analysis.summary`) from `data/leakatlas.duckdb`: {n_rows:,} "
           f"record × run rows, {n_runs} target models (3 seeds per configuration). Every number below is computed "
           "by a query on those tables; nothing is typed by hand. Brackets are 95% t-intervals over the 3 seeds.",
           "", "Attack: RMIA (offline, via ML Privacy Meter) with "
           + ", ".join(f"{r['k']} OUT reference models per record on {r['dataset']}" for r in refs.iter_rows(named=True))
           + "; LOSS as a reference-free baseline. Flags use thresholds calibrated on reference models only.",
           "", "Compute used (training, M3 Pro): " + "; ".join(
               f"{r['dataset']} {r['target_h']:.2f} h targets + {r['refs_h']:.2f} h references"
               for r in cost.iter_rows(named=True)) + ".", ""]

    out += ["## 1. Privacy, utility and cost per configuration", ""]
    for (ds, size), g in rmia.group_by(["dataset", "train_size"], maintain_order=True):
        l = loss.filter((pl.col("dataset") == ds) & (pl.col("train_size") == size))
        rows = []
        for r in g.iter_rows(named=True):
            lr = l.filter(pl.col("defense") == r["defense"]).row(0, named=True)
            eps = "–" if r["eps_spent"] is None else f"{r['eps_spent']:.2f}"
            rows.append([LABEL[r["defense"]], eps, _ci(r, "test_acc", 100), f"{r['auc']:.3f} ± {r['auc_sd']:.3f}",
                         _ci(r, "tpr_at_0p1", 100, 2), _ci(r, "tpr_at_1", 100, 2),
                         f"{100 * r['shadow_tpr_at_1']:.2f} / {100 * r['shadow_fpr_at_1']:.2f}",
                         f"{lr['auc']:.3f} / {100 * lr['tpr_at_1']:.2f}",
                         f"{r['target_sec']:.0f} + {r['refs_sec']:.0f}"])
        out += [f"### {ds}, {size:,} training records", "", _table(
            ["defense", "ε spent (RDP)", "test acc %", "RMIA AUC", "RMIA TPR@0.1% FPR (%)", "RMIA TPR@1% FPR (%)",
             "RMIA ref-calibrated TPR / realized FPR @1% (%)", "LOSS AUC / TPR@1% (%)", "train s (target + refs)"],
            rows), "", f"Pareto front (max accuracy, min TPR@1%): {', '.join(LABEL[d] for d in pareto(g))}.", ""]

    pe = query(con, "SELECT * FROM phase3_proxy_eval")
    ml = query(con, "SELECT * FROM phase3_model_level")
    stab = query(con, "SELECT * FROM phase3_stability")
    sg = query(con, "SELECT * FROM phase3_subgroups")
    pab = query(con, "SELECT dataset, defense, train_size, log_grad_norm, log_loss_ratio_rec FROM record_view "
                     "WHERE member AND seed = 1 AND NOT dev")
    rho_ab = [st.spearmanr(g["log_grad_norm"], g["log_loss_ratio_rec"]).statistic
              for _, g in pab.group_by(["dataset", "defense", "train_size"])]
    a = pe.filter(pl.col("proxy") == "log_grad_norm")
    base_rho = a.filter(pl.col("defense") == "baseline")["spearman"]
    def_rho = a.filter(pl.col("defense") != "baseline")["spearman"].drop_nans().drop_nulls()
    pooled = ml.filter((pl.col("scope") == "pooled") & (pl.col("metric") == "tpr_at_1")).row(0, named=True)
    out += ["## 2. Proxy findings (held-out: tuned on seed 0 × dev records, evaluated once on seeds 1–2 × test)", "",
            f"- **Model level (Jebreel et al.):** across {pooled['n_runs']} target runs, the test/train loss ratio has "
            f"Spearman ρ = {pooled['spearman']:.2f} with RMIA TPR@1% FPR (p = {pooled['p']:.1e}).",
            f"- **The two record-level proxies carry the same signal:** Spearman between the log gradient norm (Proxy A) "
            f"and the per-record log loss ratio (Proxy B) is {min(rho_ab):.2f}–{max(rho_ab):.2f} across all "
            f"{len(rho_ab)} configurations.",
            f"- **Direction flips with the defense:** Proxy A's rank correlation with the RMIA score is "
            f"{base_rho.min():+.2f} to {base_rho.max():+.2f} on undefended models but {def_rho.min():+.2f} to "
            f"{def_rho.max():+.2f} under the defenses, so a cutoff tuned on one regime misleads on the other.", ""]
    rows = []
    for r in a.sort(["dataset", "train_size"]).iter_rows(named=True):
        b = pe.filter((pl.col("proxy") == "log_loss_ratio_rec") & (pl.col("dataset") == r["dataset"])
                      & (pl.col("train_size") == r["train_size"]) & (pl.col("defense") == r["defense"])).row(0, named=True)
        f = lambda v, d=2: "–" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.{d}f}"
        rows.append([r["dataset"], r["train_size"], LABEL[r["defense"]], f(100 * r["base_rate"], 1),
                     f(r["spearman"]), f(b["spearman"]), f"{f(100 * r['precision'] if r['precision'] is not None else None, 1)} @ top {f(100 * r['q'] if r['q'] is not None else None, 0)}%",
                     f(r["lift"]), f(b["lift"])])
    out += [_table(["dataset", "S", "defense", "flagged members %", "ρ Proxy A", "ρ Proxy B", "Proxy A precision",
                    "lift A", "lift B"], rows),
            "", "Lift = precision / base rate (1 = no better than random). Lifts from a top-1–2% cutoff rest on "
            "~10–20 records and are noisy.", ""]

    out += ["## 3. Per-record stability across seeds (training records)", "", _table(
        ["dataset", "S", "defense", "flagged 1/3", "2/3", "3/3", "expected 3/3 if seeds were independent"],
        [[r["dataset"], r["train_size"], LABEL[r["defense"]], r["flagged_1of3"], r["flagged_2of3"], r["flagged_3of3"],
          f"{r['expected_3of3_if_independent']:.2f}"] for r in stab.iter_rows(named=True)]), ""]

    gaps = sg.group_by(["train_size", "defense", "attribute"], maintain_order=True).agg(
        pl.col("gap").first(), pl.col("gap_lo").first(), pl.col("gap_hi").first(),
        pl.col("group").sort_by("flag_rate").last().alias("top"), pl.col("flag_rate").max().alias("top_rate"),
        pl.col("group").sort_by("flag_rate").first().alias("bottom"), pl.col("flag_rate").min().alias("bottom_rate"))
    out += ["## 4. Adult subgroup exposure (flag rate among training records, max − min gap, 95% bootstrap CI)", "",
            _table(["S", "defense", "attribute", "gap (pp)", "95% CI", "most exposed", "least exposed"],
                   [[r["train_size"], LABEL[r["defense"]], r["attribute"], f"{100 * r['gap']:.2f}",
                     f"[{100 * r['gap_lo']:.2f}, {100 * r['gap_hi']:.2f}]", f"{r['top']} {100 * r['top_rate']:.2f}%",
                     f"{r['bottom']} {100 * r['bottom_rate']:.2f}%"] for r in gaps.iter_rows(named=True)]),
            "", "The max − min gap is biased upward (it cannot be negative), so compare a defense's gap with the "
            "undefended gap rather than with zero.", ""]

    small = sg.filter(pl.col("train_size") == sg["train_size"].max()).group_by("group").agg(pl.col("n").first()).sort("n")
    worst_fpr = loss.select((pl.col("shadow_fpr_at_1") * 100).max())[0, 0]
    out += ["## 5. Limitations", "",
            f"- **Scale.** Two small datasets (Adult, Fashion-MNIST), two training-set sizes each, 3 seeds, and "
            f"{', '.join(str(k) for k in refs['k'])} OUT reference models per record (Adult, Fashion-MNIST). "
            "LiRA-style studies use up to 256 shadow models; per-record scores here are noisier.",
            "- **Attack coverage.** ML Privacy Meter implements RMIA and LOSS only (no LiRA); every defense is audited "
            "with one strong reference-model attack. A stronger or adaptive attacker could find more.",
            f"- **Threshold transfer.** LOSS thresholds calibrated on references reach a realized FPR of up to "
            f"{worst_fpr:.1f}% against a 1% target; RMIA's per-example calibration transfers. Realized FPR is reported "
            "next to every shadow-calibrated TPR.",
            "- **Weak labels under defenses.** With DP-SGD and MIAShield the attack flags members at roughly the FPR "
            "rate, so the 'vulnerable' label used to score the proxies is mostly attack noise there.",
            f"- **Small subgroups.** The smallest Adult race groups have {', '.join(f'{g} n={n}' for g, n in small.head(2).iter_rows())} "
            "training records at the larger size; their intervals are wide.",
            "- **Defense implementations.** MIAShield uses only the exact-signature exclusion oracle (ESE), "
            "re-implemented in PyTorch from the authors' TensorFlow notebook. DP-SGD hyper-parameters were chosen on "
            "a defender validation split, not tuned per ε.",
            "- **Generalization.** Small MLP/CNN models trained from scratch; results may not transfer to large or "
            "pre-trained models, other data modalities, or skewed membership priors.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    con = connect(read_only=True)
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "config_table.md").write_text(
        "# Per-configuration results (mean ± std over 3 seeds)\n\nGenerated by `leakatlas.analysis` from "
        "data/leakatlas.duckdb.\n\n" + markdown(config_table(con)) + "\n")
    (RESULTS / "summary.md").write_text(summary(con))
    print("wrote results/config_table.md, results/summary.md")
